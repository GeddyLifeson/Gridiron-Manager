// Q6.3.1: the provisional fact list for the release. Every fact row in the repo (facts/*.json and the module-local
// fact files beside their data) is read, its status recomputed from its sources (never trusted as typed), and counted
// by domain and status. Blocking lines: a rule value below "Rulebook only", and a Conflict row in use.
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { FactFile, computeStatus, ruleStatusShippable, type FactRow, type FactStatus } from '../../../packages/schema/src/index.ts';

export interface FactEntry { file: string; row: FactRow; computed: FactStatus }

export interface ProvisionalReport {
  files: string[];
  skippedFiles: { file: string; reason: string }[];
  total: number;
  verified: number;
  provisional: FactEntry[];
  byDomain: Record<string, Partial<Record<FactStatus, number>>>;
  statusMismatch: FactEntry[];
  blockingRule: FactEntry[];
  blockingConflict: FactEntry[];
  /** Hash of the provisional list (ids and computed statuses): Marlon's acceptance names this hash. */
  listHash: string;
}

export const FACT_FILE = /(^facts\/[^/]+\.json$)|(^packages\/[^/]+\/(src|data)\/.*(facts[^/]*|fact-rows)\.json$)/;

export function factFiles(tracked: readonly string[]): string[] {
  return tracked.filter((f) => FACT_FILE.test(f) && !/\/test\//.test(f)).sort();
}

export function provisionalReport(root: string, files: readonly string[]): ProvisionalReport {
  const entries: FactEntry[] = [];
  const used: string[] = [];
  const skippedFiles: { file: string; reason: string }[] = [];
  for (const f of files) {
    let parsed;
    try { parsed = FactFile.safeParse(JSON.parse(readFileSync(join(root, f), 'utf8'))); } catch (e) { skippedFiles.push({ file: f, reason: `not JSON: ${(e as Error).message}` }); continue; }
    if (!parsed.success) { skippedFiles.push({ file: f, reason: 'not a fact file (FactFile schema)' }); continue; }
    used.push(f);
    for (const row of parsed.data.rows) entries.push({ file: f, row, computed: computeStatus(row) });
  }
  const byDomain: ProvisionalReport['byDomain'] = {};
  for (const e of entries) {
    const d = (byDomain[e.row.domain] ??= {});
    d[e.computed] = (d[e.computed] ?? 0) + 1;
  }
  const provisional = entries.filter((e) => e.computed !== 'Verified');
  const isRule = (e: FactEntry) => e.row.domain === 'rule' || e.row.domain === 'league-rule';
  const h = createHash('sha256');
  for (const e of [...provisional].sort((a, b) => a.row.id.localeCompare(b.row.id))) h.update(`${e.row.id}\t${e.computed}\n`);
  return {
    files: used,
    skippedFiles,
    total: entries.length,
    verified: entries.length - provisional.length,
    provisional,
    byDomain,
    statusMismatch: entries.filter((e) => e.computed !== e.row.status),
    blockingRule: entries.filter((e) => isRule(e) && !ruleStatusShippable(e.computed)),
    // usedBy is computed only for rule-set values; a Conflict row elsewhere cannot be shown unused, so it blocks too.
    blockingConflict: entries.filter((e) => e.computed === 'Conflict'),
    listHash: h.digest('hex').slice(0, 16),
  };
}

export function provisionalMarkdown(r: ProvisionalReport, commit: string): string {
  const L: string[] = [];
  L.push('# Provisional facts for the release (Q6.3.1)', '');
  L.push(`Commit ${commit.slice(0, 12)}. Generated by \`npx tsx scripts/release/gate.ts\`. Status is recomputed from each row's sources (Q6.1.2).`, '');
  L.push(`- Fact rows read: ${r.total} from ${r.files.length} files. Verified: ${r.verified}. **PROVISIONAL (not Verified): ${r.provisional.length}.**`);
  L.push(`- List hash: \`${r.listHash}\`. Marlon accepts this list or holds the release (R1.2.10 item 3); an acceptance names this hash.`);
  L.push(`- Rule values below "Rulebook only": ${r.blockingRule.length} (blocks). Conflict rows: ${r.blockingConflict.length} (blocks). Stored status differs from computed: ${r.statusMismatch.length}.`);
  if (r.skippedFiles.length) L.push(`- Files named like fact files but not in the register format (not counted): ${r.skippedFiles.map((s) => `\`${s.file}\``).join(', ')}.`);
  L.push('', '## Counts by domain and status', '');
  const statuses: FactStatus[] = ['Verified', 'Rulebook only', '2 of 3', '1 of 3', 'Unverified', 'Conflict', 'Assumption'];
  L.push(`| Domain | ${statuses.join(' | ')} |`, `| --- | ${statuses.map(() => '---').join(' | ')} |`);
  for (const d of Object.keys(r.byDomain).sort()) L.push(`| ${d} | ${statuses.map((s) => r.byDomain[d]![s] ?? 0).join(' | ')} |`);
  const section = (title: string, list: FactEntry[]) => {
    L.push('', `## ${title} (${list.length})`, '');
    if (!list.length) { L.push('None.'); return; }
    L.push('| Id | Domain | Level | Status | File | Statement |', '| --- | --- | --- | --- | --- | --- |');
    for (const e of list) L.push(`| ${e.row.id} | ${e.row.domain} | ${e.row.level} | ${e.computed} | ${e.file} | ${e.row.statement.replace(/\|/g, '/').replace(/\s+/g, ' ').slice(0, 140)} |`);
  };
  section('Blocking: rule values below "Rulebook only"', r.blockingRule);
  section('Blocking: Conflict rows', r.blockingConflict);
  section('Stored status differs from computed', r.statusMismatch);
  section('Every provisional row', r.provisional);
  return L.join('\n') + '\n';
}
