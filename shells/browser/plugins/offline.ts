// Offline support for the browser build (P2.3.2: "the game works fully offline", P2.3.1).
// After `vite build` this plugin writes two files next to the bundle:
//   sw.js                 a service worker that precaches every built file on first visit and
//                         then serves the game from the cache, with no network request.
//   (manifest is static, in public/manifest.webmanifest)
// The cache name carries a hash of the file list, so a new build gets a new cache and the old
// one is deleted on activate. Nothing here touches game state or saves (those live in OPFS or
// IndexedDB, P5.6.1); the worker only caches the program files.
import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else out.push(p);
  }
  return out;
}

export function workerSource(cacheName: string, files: string[]): string {
  return `// Generated by shells/browser/plugins/offline.ts. Do not edit.
const CACHE = ${JSON.stringify(cacheName)};
const FILES = ${JSON.stringify(files)};
self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES.map((f) => new Request(f, { cache: 'reload' })))));
});
self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('gm-shell-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});
self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    // Ignore the query string so the gate mode address (?gate=1) matches the cached page.
    const hit = await cache.match(req, { ignoreSearch: true });
    if (hit) return hit;
    if (req.mode === 'navigate') {
      const shell = await cache.match(new URL('./index.html', self.registration.scope).href);
      if (shell) return shell;
    }
    return fetch(req);
  })());
});
`;
}

export function offlinePlugin(): Plugin {
  let outDir = 'dist';
  let root = process.cwd();
  return {
    name: 'gm-offline',
    apply: 'build',
    configResolved(c) { outDir = c.build.outDir; root = c.root; },
    async closeBundle() {
      const dist = join(root, outDir);
      const files = (await walk(dist))
        .map((p) => relative(dist, p).split(sep).join('/'))
        .filter((f) => f !== 'sw.js' && !f.endsWith('.map'))
        .sort();
      const hash = createHash('sha256');
      for (const f of files) { hash.update(f); hash.update(await readFile(join(dist, f))); }
      const urls = ['./', ...files.map((f) => './' + f)];
      await writeFile(join(dist, 'sw.js'), workerSource('gm-shell-' + hash.digest('hex').slice(0, 16), urls));
    },
  };
}
