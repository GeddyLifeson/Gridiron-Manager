export const GLYPH_CHARS: readonly string[] = Object.keys(G);

/** Folds case (the faces are uppercase only, like the period generators) and maps unknown characters to '?'. */
export function normaliseChar(ch: string): string {
  const up = ch.toUpperCase();
  return up in G ? up : '?';
}

/** The 7 rows of a glyph as booleans, row 0 at the top. */
export function glyphBits(ch: string): boolean[][] {
  return G[normaliseChar(ch)]!.map((row) => [...row].map((c) => c === '#'));
}

/** Text as a run of normalised characters (fixed pitch, so the run length is the cell count). */
export function normaliseText(text: string): string[] {
  return [...text].map(normaliseChar);
}
