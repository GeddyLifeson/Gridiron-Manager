# Builds src/gameplan/reference-college-2024.ts (G7.2.3 college league reference table) from the cfbfastR
# 2024 play-by-play release (sportsdataverse-data, tag cfbfastR_cfb_pbp, play_by_play_2024.parquet; the
# plays come from ESPN through the CollegeFootballData pipeline).
# Run: python3 -I build_reference_college.py <play_by_play_2024.parquet> <out.ts>   (needs pyarrow)
# Rows kept: regular season, both teams FBS, rush or pass plays (sacks, interceptions, fumbles and scoring
# plays included) with a down 1 to 4. Kneels and spikes are left out by their play text ("kneel", "spike"),
# the same plays nflverse gives their own play_type in the pro table. Tries have no down and drop out.
# Cell key as the pro table: down, distance (capped at 25), yards to goal, half-seconds bucket
# (<=120, <=240, <=480, more), half (1, 2, overtime), no-huddle flag (always 0: the release has no
# no-huddle column, so tempo is an unseen field of this table).
import sys, re, collections
import pyarrow.parquet as pq

def b36(n, width=0):
    s = ''
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    while True:
        s = digits[n % 36] + s
        n //= 36
        if n == 0:
            break
    return s.rjust(width, '0')

src, out = sys.argv[1], sys.argv[2]
cols = ['game_id', 'season_type', 'home_team_division', 'away_team_division', 'down', 'distance', 'yards_to_goal',
        'rush', 'pass', 'period', 'pos_team', 'drive_id', 'TimeSecsRem', 'play_text']
rows = pq.read_table(src, columns=cols).to_pylist()
skip = re.compile(r'\bkneel|\bspike', re.I)
cells = collections.Counter()
games, drives = set(), set()
for x in rows:
    if x['season_type'] != 'regular' or x['home_team_division'] != 'fbs' or x['away_team_division'] != 'fbs':
        continue
    games.add(x['game_id'])
    if x['pos_team'] and x['drive_id']:
        drives.add((x['game_id'], x['pos_team'], x['drive_id']))
    if not (x['rush'] == 1 or x['pass'] == 1) or x['down'] not in (1, 2, 3, 4):
        continue
    if x['play_text'] and skip.search(x['play_text']):
        continue
    if x['distance'] is None or x['yards_to_goal'] is None:
        continue
    down = int(x['down']); dist = max(0, min(int(x['distance']), 25)); ytg = max(1, min(int(x['yards_to_goal']), 99))
    hs = int(x['TimeSecsRem'] or 0); q = int(x['period'])
    hb = 0 if hs <= 120 else 1 if hs <= 240 else 2 if hs <= 480 else 3
    half = 1 if q <= 2 else 2 if q <= 4 else 3
    cells[(down, dist, ytg, hb, half, 0)] += 1
tg = 2 * len(games)
enc = ';'.join(f'{d}{b36(t)}{b36(y, 2)}{hb}{h}{nh}{b36(n)}' for (d, t, y, hb, h, nh), n in sorted(cells.items()))
with open(out, 'w') as f:
    f.write('// GENERATED by test/gameplan/build_reference_college.py from the cfbfastR 2024 play-by-play release\n')
    f.write('// (https://github.com/sportsdataverse/sportsdataverse-data/releases/tag/cfbfastR_cfb_pbp). Do not edit by hand. See reference.ts.\n')
    f.write(f'export const COLLEGE_2024_TEAM_GAMES = {tg};\n')
    f.write(f'export const COLLEGE_2024_DRIVES = {len(drives)};\n')
    f.write(f'export const COLLEGE_2024_CELLS =\n  {enc!r};\n')
print(tg, len(cells), sum(cells.values()), len(drives))
