# Builds src/gameplan/reference-pro-2024.ts (G7.2.3 league reference table) from the nflverse 2024
# play-by-play release. Run: python3 -I build_reference.py <play_by_play_2024.csv.gz> <out.ts>
# Source: https://github.com/nflverse/nflverse-data/releases/tag/pbp (play_by_play_2024.csv.gz).
# Rows kept: regular season, play_type run or pass, two-point tries excluded (kneels and spikes have their
# own play_type and so are excluded), plays with a down. Cell key: down, distance (capped at 25), yards to
# goal, half-seconds bucket (<=120, <=240, <=480, more), half (1, 2, overtime), no-huddle flag.
import csv, gzip, sys, collections

def b36(n, width=0):
    s = ''
    digits = '0123456789abcdefghijklmnopqrstuvwxyz'
    while True:
        s = digits[n % 36] + s
        n //= 36
        if n == 0:
            break
    return s.rjust(width, '0')

src, out = sys.argv[1], sys.argv[2]
cells = collections.Counter()
games = set()
drives = set()
for x in csv.DictReader(gzip.open(src, 'rt')):
    if x['season_type'] != 'REG':
        continue
    games.add(x['game_id'])
    if x['posteam'] and x['drive']:
        drives.add((x['game_id'], x['posteam'], x['drive']))
    if x['two_point_attempt'] == '1' or x['play_type'] not in ('run', 'pass') or x['down'] == '':
        continue
    down = int(float(x['down'])); dist = min(int(float(x['ydstogo'])), 25); ytg = int(float(x['yardline_100']))
    hs = int(float(x['half_seconds_remaining'] or 0)); q = int(x['qtr'])
    hb = 0 if hs <= 120 else 1 if hs <= 240 else 2 if hs <= 480 else 3
    half = 1 if q <= 2 else 2 if q <= 4 else 3
    nh = 1 if x['no_huddle'] == '1' else 0
    cells[(down, dist, ytg, hb, half, nh)] += 1
tg = 2 * len(games)
enc = ';'.join(f'{d}{b36(t)}{b36(y, 2)}{hb}{h}{nh}{b36(n)}' for (d, t, y, hb, h, nh), n in sorted(cells.items()))
with open(out, 'w') as f:
    f.write('// GENERATED by test/gameplan/build_reference.py from the nflverse 2024 play-by-play release\n')
    f.write('// (https://github.com/nflverse/nflverse-data/releases/tag/pbp). Do not edit by hand. See reference.ts.\n')
    f.write(f'export const PRO_2024_TEAM_GAMES = {tg};\n')
    f.write(f'export const PRO_2024_DRIVES = {len(drives)};\n')
    f.write(f'export const PRO_2024_CELLS =\n  {enc!r};\n'.replace("'", "'"))
print(tg, len(cells), sum(cells.values()), len(drives))
